-- One table for the whole MenuItem hierarchy (SINGLE_TABLE inheritance).
-- item_type is the discriminator column: 'FOOD' -> FoodItem, 'BEVERAGE' -> Beverage
CREATE TABLE menu_items (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,   -- GenerationType.IDENTITY
    item_type    VARCHAR(31)  NOT NULL CHECK (item_type IN ('FOOD', 'BEVERAGE')),
    name         VARCHAR(100) NOT NULL,
    description  VARCHAR(255),
    price        DOUBLE PRECISION NOT NULL,
    category     VARCHAR(50)  NOT NULL,
    available    BOOLEAN      NOT NULL,
    -- FoodItem columns (NULL for beverages)
    vegetarian   BOOLEAN,
    spice_level  VARCHAR(10),
    -- Beverage columns (NULL for food)
    volume_ml    INTEGER,
    served_cold  BOOLEAN
);

CREATE TABLE customer_orders (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_name VARCHAR(100) NOT NULL,
    table_number  INTEGER      NOT NULL,
    status        VARCHAR(20)  NOT NULL
                  CHECK (status IN ('PLACED', 'PREPARING', 'SERVED', 'PAID', 'CANCELLED')),
    order_time    TIMESTAMP(6) NOT NULL,
    subtotal      DOUBLE PRECISION NOT NULL
);

-- One row per line of an order. Links an order (many-to-one) to a menu item (many-to-one).
CREATE TABLE order_items (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     BIGINT  NOT NULL REFERENCES customer_orders (id),
    menu_item_id BIGINT  NOT NULL REFERENCES menu_items (id),
    quantity     INTEGER NOT NULL,
    unit_price   DOUBLE PRECISION NOT NULL
);
